function citationDuJour(date = new Date()) {
  const debut = new Date(date.getFullYear(), 0, 0);
  const jour = Math.floor((date - debut) / 86_400_000);
  return CITATIONS[(jour + date.getFullYear()) % CITATIONS.length];
}
